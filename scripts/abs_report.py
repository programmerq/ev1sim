# Phase-segment statistics
# ---------------------------------------------------------------------------

def phase_stats(rows: list[dict], col: str,
                brake_idx: int, end_idx: int) -> dict:
    """% of brake event spent in APPLY / HOLD / DUMP / stale, plus
    transition count (excluding stale boundaries)."""
    if brake_idx < 0:
        return {"apply": 0.0, "hold": 0.0, "dump": 0.0,
                "stale": 0.0, "transitions": 0}
    durations = {0: 0.0, 1: 0.0, 2: 0.0, -1: 0.0}
    transitions = 0
    prev = int(rows[brake_idx].get(col, -1))
    prev_t = rows[brake_idx]["sim_time_s"]
    for r in rows[brake_idx + 1:end_idx + 1]:
        t = r["sim_time_s"]
        durations[prev] = durations.get(prev, 0.0) + (t - prev_t)
        cur = int(r.get(col, -1))
        if cur != prev and cur != -1 and prev != -1:
            transitions += 1
        prev_t = t
        prev = cur
    total = sum(durations.values())
    if total == 0:
        return {"apply": 0.0, "hold": 0.0, "dump": 0.0,
                "stale": 0.0, "transitions": 0}
    return {
        "apply":       100.0 * durations.get(0,  0.0) / total,
        "hold":        100.0 * durations.get(1,  0.0) / total,
        "dump":        100.0 * durations.get(2,  0.0) / total,
        "stale":       100.0 * durations.get(-1, 0.0) / total,
        "transitions": transitions,
    }


def yaw_drift_deg(rows: list[dict],
                  brake_idx: int, end_idx: int) -> float:
    """Integrate yaw_rate over the brake event → total heading change."""
    import math
    if brake_idx < 0 or brake_idx >= end_idx:
        return 0.0
    drift = 0.0
    for i in range(brake_idx, end_idx):
        dt = rows[i+1]["sim_time_s"] - rows[i]["sim_time_s"]
        drift += rows[i]["yaw_rate"] * dt
    return drift * (180.0 / math.pi)


