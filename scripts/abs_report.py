def chart_speed_compare(on_rows: list[dict], off_rows: list[dict],
                         on_brake: int, on_end: int,
                         off_brake: int, off_end: int,
                         title: str) -> str:
    """Vehicle-speed comparison — BTCM-on overlaid on BTCM-off."""
    svg = Svg(w=720, h=220, title=title)

    on_pts  = [(r["sim_time_s"], r["speed_mps"])
               for r in on_rows[on_brake:on_end+1]]   if on_brake  >= 0 else []
    off_pts = [(r["sim_time_s"], r["speed_mps"])
               for r in off_rows[off_brake:off_end+1]] if off_brake >= 0 else []
    if not on_pts and not off_pts:
        svg.axes(0, 1, 0, 1, "t [s]", "v [m/s]")
        return svg.render()

    xs = [p[0] for p in on_pts] + [p[0] for p in off_pts]
    ys = [p[1] for p in on_pts] + [p[1] for p in off_pts]
    ax = svg.axes(min(xs), max(xs), 0, max(ys) * 1.05,
                  x_label="t [s]", y_label="v [m/s]")
    svg.polyline(ax, off_pts, color="#e08a3c", width=1.4)
    svg.polyline(ax, on_pts,  color="#3470c0", width=1.4)
    svg.legend(ax, [("BTCM-on", "#3470c0"), ("BTCM-off", "#e08a3c")])
    return svg.render()


def chart_per_wheel_speed(rows: list[dict], brake_idx: int, end_idx: int,
                          title: str) -> str:
    """Per-wheel ground speed (omega × radius) plus chassis speed."""
    svg = Svg(w=720, h=240, title=title)
    if brake_idx < 0:
        svg.axes(0, 1, 0, 1, "t [s]", "m/s")
        return svg.render()
    sub = rows[brake_idx:end_idx+1]
    chassis  = [(r["sim_time_s"], r["speed_mps"])              for r in sub]
    wheel_fl = [(r["sim_time_s"], abs(r["wheel_omega_fl"]) * TIRE_RADIUS_M) for r in sub]
    wheel_fr = [(r["sim_time_s"], abs(r["wheel_omega_fr"]) * TIRE_RADIUS_M) for r in sub]
    wheel_rl = [(r["sim_time_s"], abs(r["wheel_omega_rl"]) * TIRE_RADIUS_M) for r in sub]
    wheel_rr = [(r["sim_time_s"], abs(r["wheel_omega_rr"]) * TIRE_RADIUS_M) for r in sub]
    xs = [p[0] for p in chassis]
    ys = ([p[1] for p in chassis]
          + [p[1] for p in wheel_fl]
          + [p[1] for p in wheel_fr]
          + [p[1] for p in wheel_rl]
          + [p[1] for p in wheel_rr])
    ax = svg.axes(min(xs), max(xs), 0, max(ys) * 1.05,
                  x_label="t [s]", y_label="m/s")
    svg.polyline(ax, chassis,  color="#000", width=1.6)
    svg.polyline(ax, wheel_fl, color="#c0392b", width=1.0)
    svg.polyline(ax, wheel_fr, color="#27ae60", width=1.0)
    svg.polyline(ax, wheel_rl, color="#2980b9", width=1.0)
    svg.polyline(ax, wheel_rr, color="#8e44ad", width=1.0)
    svg.legend(ax, [
        ("chassis",  "#000"),
        ("FL wheel", "#c0392b"),
        ("FR wheel", "#27ae60"),
        ("RL wheel", "#2980b9"),
        ("RR wheel", "#8e44ad"),
    ])
    return svg.render()


