def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 1
    out_path = Path(argv[1])
    out_md_dir = out_path.parent
    charts_dir = out_md_dir / f"{out_path.stem}.charts"

    parsed: dict[str, dict] = {}
    on_rows_by:  dict[str, list[dict]] = {}
    off_rows_by: dict[str, list[dict]] = {}
    missing: list[str] = []
    for t in TESTS:
        d = Path(SUMMARY_DIR_TMPL.format(test=t))
        s = d / "summary.txt"
        on_csv  = d / "abs_btcm_on.csv"
        off_csv = d / "abs_btcm_off.csv"
        if not (s.exists() and on_csv.exists() and off_csv.exists()):
            missing.append(t)
            continue
        parsed[t]      = parse_summary(s.read_text())
        on_rows_by[t]  = load_csv(on_csv)
        off_rows_by[t] = load_csv(off_csv)

    if missing:
        for m in missing:
            print(f"warning: missing source data for {m} — re-run "
                  f"scripts/run_abs_compare.sh {m}", file=sys.stderr)

    ts = datetime.datetime.now().strftime("%Y-%m-%d %H:%M %Z").strip()

    lines: list[str] = []
    lines.append("# EV1 ABS validation — engineering report")
    lines.append("")
    lines.append(f"_Generated {ts} by `scripts/abs_report.py`._")
    lines.append("")
    lines.append("This report aggregates the four standard ABS validation")
    lines.append("scenarios.  Each scenario gets its own section with setup,")
    lines.append("numerical result tables, and a stack of charts: vehicle")
    lines.append("speed, per-wheel ground speed, slip ratios, ABS phase")
    lines.append("timeline, yaw rate, and (for `split_mu`) trajectory.")
    lines.append("")
    lines.append("Source data: `/tmp/ev1sim_abs_<test>/{summary.txt,")
    lines.append("abs_btcm_{on,off}.csv}`.  Refresh with")
    lines.append("`for t in high_mu low_mu mu_jump split_mu; do "
                 "./scripts/run_abs_compare.sh $t; done` and re-run this")
    lines.append("script.")
    lines.append("")

    # Top-of-file summary table.
    lines.append("## Headline table")
    lines.append("")
    lines.append("| Test | BTCM-on stop | BTCM-off stop | Δ stop dist | "
                 "ABS events FL/FR | yaw drift (on / off) |")
    lines.append("|---|---|---|---:|---:|---|")
    import math
    for t in TESTS:
        d = parsed.get(t)
        if d is None:
            lines.append(f"| {t} | (no data) | (no data) | — | — | — |")
            continue
        on  = stop_str(d, "on")
        off = stop_str(d, "off")
        delta = "—"
        if d.get("on_stopped") and d.get("off_stopped"):
            delta = f"{d['on_stop_dist'] - d['off_stop_dist']:+.1f} m"
        on_brake_idx, on_end_idx   = find_brake_indices(on_rows_by[t])
        off_brake_idx, off_end_idx = find_brake_indices(off_rows_by[t])
        on_yaw  = yaw_drift_deg(on_rows_by[t],  on_brake_idx,  on_end_idx)
        off_yaw = yaw_drift_deg(off_rows_by[t], off_brake_idx, off_end_idx)
        lines.append(
            f"| {t} | {on} | {off} | {delta} | "
            f"{d.get('on_fl_events', 0)} / {d.get('on_fr_events', 0)} | "
            f"{on_yaw:+.2f}° / {off_yaw:+.2f}° |")
    lines.append("")
    lines.append("Δ stop dist > 0 means BTCM-on took *longer* than BTCM-off.")
    lines.append("Yaw drift > 0 = car rotated counter-clockwise (toward driver");
    lines.append("left).  On `split_mu` the car drifts toward the asphalt side")
    lines.append("(positive in our coordinate frame).")
    lines.append("")

    # Per-scenario sections.
    for t in TESTS:
        if t not in parsed:
            lines.append(f"## `{t}`")
            lines.append("")
            lines.append("_(no data — re-run `scripts/run_abs_compare.sh "
                         f"{t}` then re-run this script)_")
            lines.append("")
            continue
        lines.extend(write_scenario_section(
            t, parsed[t], on_rows_by[t], off_rows_by[t],
            charts_dir, out_md_dir))

    out_path.write_text("\n".join(lines) + "\n")
    print(f"[abs-report] wrote {out_path}")
    print(f"[abs-report] charts → {charts_dir}/")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
