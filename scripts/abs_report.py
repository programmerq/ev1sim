class Svg:
    """Minimal SVG builder with linear-axis line charts.

    Coordinates: caller passes data-space x/y; we map to pixel-space
    based on min/max, leaving a fixed-pixel margin for axes/labels.
    """

    def __init__(self, w: int = 720, h: int = 220, title: str = ""):
        self.w = w
        self.h = h
        self.title = title
        self.parts: list[str] = []
        self.parts.append(
            f'<svg xmlns="http://www.w3.org/2000/svg" '
            f'viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
            f'font-family="ui-monospace,Consolas,Menlo,monospace" '
            f'font-size="11">')
        self.parts.append('<rect width="100%" height="100%" fill="#ffffff"/>')
        if title:
            self.parts.append(
                f'<text x="{w/2}" y="14" text-anchor="middle" '
                f'font-size="12" font-weight="bold">{escape(title)}</text>')

    def axes(self,
             x_min: float, x_max: float,
             y_min: float, y_max: float,
             x_label: str = "", y_label: str = "",
             margin_l: int = 56, margin_r: int = 12,
             margin_t: int = 24, margin_b: int = 36) -> dict:
        """Draw axis box + ticks.  Returns a `to_px` dict for plotting."""
        plot_x0 = margin_l
        plot_y0 = margin_t
        plot_w  = self.w - margin_l - margin_r
        plot_h  = self.h - margin_t - margin_b

        if x_max <= x_min:
            x_max = x_min + 1.0
        if y_max <= y_min:
            y_max = y_min + 1.0

        # Axis frame.
        self.parts.append(
            f'<rect x="{plot_x0}" y="{plot_y0}" width="{plot_w}" '
            f'height="{plot_h}" fill="none" stroke="#444" stroke-width="0.5"/>')

        # X ticks (5).
        for i in range(6):
            xv = x_min + (x_max - x_min) * i / 5
            xp = plot_x0 + plot_w * i / 5
            self.parts.append(
                f'<line x1="{xp:.1f}" y1="{plot_y0+plot_h}" '
                f'x2="{xp:.1f}" y2="{plot_y0+plot_h+3}" stroke="#444"/>')
            self.parts.append(
                f'<text x="{xp:.1f}" y="{plot_y0+plot_h+14}" '
                f'text-anchor="middle" fill="#333">{xv:.2f}</text>')
        # Y ticks (5).
        for i in range(6):
            yv = y_min + (y_max - y_min) * i / 5
            yp = plot_y0 + plot_h - plot_h * i / 5
            self.parts.append(
                f'<line x1="{plot_x0-3}" y1="{yp:.1f}" '
                f'x2="{plot_x0}" y2="{yp:.1f}" stroke="#444"/>')
            self.parts.append(
                f'<text x="{plot_x0-5}" y="{yp:.1f}" '
                f'text-anchor="end" dominant-baseline="middle" '
                f'fill="#333">{yv:.2f}</text>')
        if x_label:
            self.parts.append(
                f'<text x="{plot_x0+plot_w/2}" y="{self.h-6}" '
                f'text-anchor="middle" fill="#333">{escape(x_label)}</text>')
        if y_label:
            self.parts.append(
                f'<text transform="translate(14,{plot_y0+plot_h/2}) rotate(-90)" '
                f'text-anchor="middle" fill="#333">{escape(y_label)}</text>')

        return {
            "x0": plot_x0, "y0": plot_y0,
            "w":  plot_w,  "h":  plot_h,
            "x_min": x_min, "x_max": x_max,
            "y_min": y_min, "y_max": y_max,
        }

    @staticmethod
    def to_px(ax: dict, x: float, y: float) -> tuple[float, float]:
        u = (x - ax["x_min"]) / (ax["x_max"] - ax["x_min"])
        v = (y - ax["y_min"]) / (ax["y_max"] - ax["y_min"])
        return ax["x0"] + ax["w"] * u, ax["y0"] + ax["h"] * (1 - v)

    def polyline(self, ax: dict, points: list[tuple[float, float]],
                 color: str, width: float = 1.2,
                 dash: Optional[str] = None) -> None:
        if not points:
            return
        pts = [self.to_px(ax, x, y) for x, y in points]
        d = " ".join(f"{x:.1f},{y:.1f}" for x, y in pts)
        dash_attr = f' stroke-dasharray="{dash}"' if dash else ""
        self.parts.append(
            f'<polyline fill="none" stroke="{color}" stroke-width="{width}" '
            f'points="{d}"{dash_attr}/>')

    def hline(self, ax: dict, y: float, color: str = "#999",
              dash: str = "3 3", label: str = "") -> None:
        x0, _ = self.to_px(ax, ax["x_min"], y)
        x1, yp = self.to_px(ax, ax["x_max"], y)
        self.parts.append(
            f'<line x1="{x0:.1f}" y1="{yp:.1f}" x2="{x1:.1f}" y2="{yp:.1f}" '
            f'stroke="{color}" stroke-width="0.7" stroke-dasharray="{dash}"/>')
        if label:
            self.parts.append(
                f'<text x="{x1-2:.1f}" y="{yp-2:.1f}" text-anchor="end" '
                f'fill="{color}">{escape(label)}</text>')

    def vline(self, ax: dict, x: float, color: str = "#888",
              dash: str = "2 3", label: str = "") -> None:
        xp, y0 = self.to_px(ax, x, ax["y_max"])
        _,  y1 = self.to_px(ax, x, ax["y_min"])
        self.parts.append(
            f'<line x1="{xp:.1f}" y1="{y0:.1f}" x2="{xp:.1f}" y2="{y1:.1f}" '
            f'stroke="{color}" stroke-width="0.7" stroke-dasharray="{dash}"/>')
        if label:
            self.parts.append(
                f'<text x="{xp+3:.1f}" y="{y0+10:.1f}" fill="{color}">'
                f'{escape(label)}</text>')

    def legend(self, ax: dict, items: list[tuple[str, str]]) -> None:
        x = ax["x0"] + 8
        y = ax["y0"] + 12
        for label, color in items:
            self.parts.append(
                f'<rect x="{x}" y="{y-7}" width="10" height="3" fill="{color}"/>')
            self.parts.append(
                f'<text x="{x+14}" y="{y-1}" fill="#222">'
                f'{escape(label)}</text>')
            y += 13

    def phase_band(self, ax: dict, t_pairs: list[tuple[float, float, int]],
                   y_band_top: float, band_height_px: int = 14,
                   label: str = "") -> None:
        """Render an ABS-phase Gantt band.

        t_pairs: (t_start, t_end, phase) — phase 0=APPLY, 1=HOLD, 2=DUMP, -1=stale.
        y_band_top: data-space y-coordinate for the top of the band.
        """
        colors = {0: "#9bda9b", 1: "#ffd66e", 2: "#f08a8a", -1: "#dddddd"}
        # Convert y_band_top to pixel and grow downward.
        x0, yp_top = self.to_px(ax, ax["x_min"], y_band_top)
        for t0, t1, ph in t_pairs:
            xa, _ = self.to_px(ax, t0, y_band_top)
            xb, _ = self.to_px(ax, t1, y_band_top)
            xa = max(xa, ax["x0"])
            xb = min(xb, ax["x0"] + ax["w"])
            if xb <= xa:
                continue
            self.parts.append(
                f'<rect x="{xa:.1f}" y="{yp_top:.1f}" '
                f'width="{xb-xa:.1f}" height="{band_height_px}" '
                f'fill="{colors.get(ph, "#ccc")}" stroke="#444" '
                f'stroke-width="0.3"/>')
        if label:
            self.parts.append(
                f'<text x="{ax["x0"]+ax["w"]+4}" y="{yp_top+band_height_px-3}" '
                f'fill="#333">{escape(label)}</text>')

    def render(self) -> str:
        self.parts.append("</svg>")
        return "\n".join(self.parts) + "\n"


def escape(s: str) -> str:
    return (s.replace("&", "&amp;")
             .replace("<", "&lt;")
             .replace(">", "&gt;"))


