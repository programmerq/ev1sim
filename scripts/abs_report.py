def load_csv(path: Path) -> list[dict]:
    rows: list[dict] = []
    with path.open() as f:
        for r in csv.DictReader(f):
            try:
                rows.append({k: float(v) for k, v in r.items()})
            except ValueError:
                rows.append(r)
    return rows


def find_brake_indices(rows: list[dict]) -> tuple[int, int]:
    """Return (brake_on_idx, brake_off_idx) in rows.  -1 if not found."""
    on_idx, off_idx = -1, -1
    for i, r in enumerate(rows):
        fb = r.get("applied_front_brake", 0)
        if on_idx < 0 and fb > 0.5:
            on_idx = i
        elif on_idx >= 0 and off_idx < 0 and fb < 0.5:
            off_idx = i
    if off_idx < 0:
        off_idx = len(rows) - 1
    return on_idx, off_idx


