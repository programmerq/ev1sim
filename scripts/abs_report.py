def phase_segments(rows: list[dict], col: str,
                   start_idx: int, end_idx: int) -> list[tuple[float, float, int]]:
    """Compress consecutive same-phase samples into (t_start, t_end, phase)."""
    segs: list[tuple[float, float, int]] = []
    if start_idx < 0:
        return segs
    cur_phase = int(rows[start_idx].get(col, -1))
    seg_start = rows[start_idx]["sim_time_s"]
    for i in range(start_idx + 1, end_idx + 1):
        ph = int(rows[i].get(col, -1))
        if ph != cur_phase:
            segs.append((seg_start, rows[i]["sim_time_s"], cur_phase))
            seg_start = rows[i]["sim_time_s"]
            cur_phase = ph
    segs.append((seg_start, rows[end_idx]["sim_time_s"], cur_phase))
    return segs


def chart_abs_phase_timeline(rows: list[dict], brake_idx: int, end_idx: int,
                              title: str) -> str:
    """Two-band Gantt: FL on top, FR below.  Below them a per-segment count
    summary of how many APPLY/HOLD/DUMP transitions happened."""
    svg = Svg(w=720, h=180, title=title)
    if brake_idx < 0:
        svg.axes(0, 1, 0, 1, "t [s]", "")
        return svg.render()
    t_min = rows[brake_idx]["sim_time_s"]
    t_max = rows[end_idx]["sim_time_s"]
    ax = svg.axes(t_min, t_max, 0, 1, x_label="t [s]", y_label="")

    # Band y-position chosen in data space then mapped.
    fl_segs = phase_segments(rows, "abs_phase_fl", brake_idx, end_idx)
    fr_segs = phase_segments(rows, "abs_phase_fr", brake_idx, end_idx)
    svg.phase_band(ax, fl_segs, y_band_top=0.85, label="FL")
    svg.phase_band(ax, fr_segs, y_band_top=0.55, label="FR")

    # Legend.
    svg.parts.append(
        f'<rect x="{ax["x0"]+8}" y="{ax["y0"]+5}" width="10" height="8" '
        f'fill="#9bda9b" stroke="#444" stroke-width="0.3"/>')
    svg.parts.append(
        f'<text x="{ax["x0"]+22}" y="{ax["y0"]+12}" fill="#222">APPLY</text>')
    svg.parts.append(
        f'<rect x="{ax["x0"]+72}" y="{ax["y0"]+5}" width="10" height="8" '
        f'fill="#ffd66e" stroke="#444" stroke-width="0.3"/>')
    svg.parts.append(
        f'<text x="{ax["x0"]+86}" y="{ax["y0"]+12}" fill="#222">HOLD</text>')
    svg.parts.append(
        f'<rect x="{ax["x0"]+128}" y="{ax["y0"]+5}" width="10" height="8" '
        f'fill="#f08a8a" stroke="#444" stroke-width="0.3"/>')
    svg.parts.append(
        f'<text x="{ax["x0"]+142}" y="{ax["y0"]+12}" fill="#222">DUMP</text>')
    svg.parts.append(
        f'<rect x="{ax["x0"]+184}" y="{ax["y0"]+5}" width="10" height="8" '
        f'fill="#dddddd" stroke="#444" stroke-width="0.3"/>')
    svg.parts.append(
        f'<text x="{ax["x0"]+198}" y="{ax["y0"]+12}" fill="#222">stale</text>')

    return svg.render()


def chart_rear_modulation(rows: list[dict], brake_idx: int, end_idx: int,
                            title: str) -> str:
    """Rear axle ABS modulation, shown as the actual EMB motor command.

    Unlike the front axle (discrete APPLY/HOLD/DUMP solenoid phases),
    the rear EMB has a continuous motor-current command in [-1, +1]:
        +1 = full apply (motor pushing the shoes outward)
         0 = idle / hold position
        -1 = full release (motor retracting the shoes)
    The btcm_rear module translates the same ABS phase decisions the
    front axle uses into this signed command, so this chart shows
    "what the BTCM is telling the rear axle to do" — the analog of
    the front phase Gantt.
    """
    svg = Svg(w=720, h=220, title=title)
    if brake_idx < 0:
        svg.axes(0, 1, -1.1, 1.1, "t [s]", "EMB cmd")
        return svg.render()
    sub = rows[brake_idx:end_idx+1]
    lr = [(r["sim_time_s"], r["emb_cmd_lr"]) for r in sub]
    rr = [(r["sim_time_s"], r["emb_cmd_rr"]) for r in sub]
    xs = [p[0] for p in lr]
    ax = svg.axes(min(xs), max(xs), -1.1, 1.1,
                  x_label="t [s]", y_label="EMB cmd [-1..+1]")
    svg.hline(ax, 0, color="#aaa", dash="1 0")
    svg.hline(ax, 0.05,  color="#9bda9b", label="apply deadband")
