def stop_str(d: dict, prefix: str) -> str:
    if d.get(f"{prefix}_stopped"):
        return f"{d['{}_stop_dist'.format(prefix)]:.2f} m / {d['{}_stop_t'.format(prefix)]:.2f} s"
    if (v := d.get(f"{prefix}_final_v")) is not None:
        return f"didn't stop, v\\_f = {v:.2f} m/s"
    return "—"


def write_scenario_section(t: str, d: dict,
                           on_rows: list[dict], off_rows: list[dict],
                           charts_dir: Path,
                           out_md_dir: Path) -> list[str]:
    """Emit a per-scenario section.  Generates SVG charts in charts_dir
    and references them by relative path from out_md_dir."""
    setup = SETUP[t]
    on_brake, on_end   = find_brake_indices(on_rows)
    off_brake, off_end = find_brake_indices(off_rows)

    fl_phase = phase_stats(on_rows, "abs_phase_fl", on_brake, on_end)
    fr_phase = phase_stats(on_rows, "abs_phase_fr", on_brake, on_end)
    on_yaw   = yaw_drift_deg(on_rows,  on_brake,  on_end)
    off_yaw  = yaw_drift_deg(off_rows, off_brake, off_end)

    def write_svg(name: str, content: str) -> str:
        p = charts_dir / f"{t}_{name}.svg"
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content)
        rel = p.relative_to(out_md_dir)
        return str(rel)

    speed_svg     = write_svg("speed",
                              chart_speed_compare(on_rows, off_rows,
                                                   on_brake, on_end,
                                                   off_brake, off_end,
                                                   f"{t} — vehicle speed during brake event"))
    wheel_svg     = write_svg("wheel_speed",
                              chart_per_wheel_speed(on_rows, on_brake, on_end,
                                                     f"{t} — chassis vs per-wheel ground speed (BTCM-on)"))
    slip_svg      = write_svg("slip",
                              chart_slip_ratios(on_rows, on_brake, on_end,
                                                 f"{t} — slip ratios (BTCM-on)"))
    phase_svg     = write_svg("phase",
                              chart_abs_phase_timeline(on_rows, on_brake, on_end,
                                                        f"{t} — front ABS phase timeline (BTCM-on)"))
    yaw_svg       = write_svg("yaw",
                              chart_yaw_rate(on_rows, on_brake, on_end,
                                              f"{t} — yaw rate during brake event (BTCM-on)"))

    lines: list[str] = []
    lines.append(f"## `{t}`")
    lines.append("")
    lines.append("### Setup")
    lines.append("")
    lines.append("| Field | Value |")
    lines.append("|---|---|")
    lines.append(f"| Surface | {setup['surface']} |")
    lines.append(f"| Approach | {setup['approach']} |")
    lines.append(f"| Brake fires | {setup['brake_at']} |")
    lines.append(f"| Validates | {setup['checks']} |")
    lines.append("")

    lines.append("### Result summary (BTCM-on vs BTCM-off)")
    lines.append("")
    lines.append("| Metric | BTCM-on | BTCM-off |")
    lines.append("|---|---|---|")
    lines.append(f"| Brake-on at | t = {d.get('on_brake_t', 0):.2f} s, v = {d.get('on_brake_v', 0):.2f} m/s | t = {d.get('off_brake_t', 0):.2f} s, v = {d.get('off_brake_v', 0):.2f} m/s |")
    lines.append(f"| Stop result | {stop_str(d, 'on')} | {stop_str(d, 'off')} |")
    lines.append(f"| FL events | {d.get('on_fl_events', 0)} | {d.get('off_fl_events', 0)} |")
    lines.append(f"| FR events | {d.get('on_fr_events', 0)} | {d.get('off_fr_events', 0)} |")
    lines.append(f"| Yaw drift over brake | {on_yaw:+.2f}° | {off_yaw:+.2f}° |")
    lines.append("")

    lines.append("### Per-wheel slip statistics (BTCM-on)")
    lines.append("")
    lines.append("| Wheel | peak | mean | time-locked |")
    lines.append("|---|---:|---:|---:|")
    for w in ("fl", "fr", "rl", "rr"):
        lines.append(
            f"| {w.upper()} | {d.get(f'on_{w}_peak', 0):.3f} | "
            f"{d.get(f'on_{w}_mean', 0):.3f} | "
            f"{d.get(f'on_{w}_locked', 0):.1f}% |")
    lines.append("")

    lines.append("### Front ABS phase distribution during brake event (BTCM-on)")
    lines.append("")
    lines.append("| Wheel | APPLY | HOLD | DUMP | stale | phase transitions |")
    lines.append("|---|---:|---:|---:|---:|---:|")
    lines.append(
        f"| FL | {fl_phase['apply']:.1f}% | {fl_phase['hold']:.1f}% | "
        f"{fl_phase['dump']:.1f}% | {fl_phase['stale']:.1f}% | "
        f"{fl_phase['transitions']} |")
    lines.append(
        f"| FR | {fr_phase['apply']:.1f}% | {fr_phase['hold']:.1f}% | "
        f"{fr_phase['dump']:.1f}% | {fr_phase['stale']:.1f}% | "
        f"{fr_phase['transitions']} |")
    lines.append("")

    lines.append("### Charts")
    lines.append("")
    lines.append(f"![speed compare]({speed_svg})")
    lines.append("")
    lines.append(f"![per-wheel speeds]({wheel_svg})")
    lines.append("")
    lines.append(f"![slip ratios]({slip_svg})")
    lines.append("")
    lines.append(f"![ABS phase timeline]({phase_svg})")
    lines.append("")
    lines.append(f"![yaw rate]({yaw_svg})")
    lines.append("")

    if t == "split_mu":
        traj_svg = write_svg("trajectory",
                              chart_trajectory(on_rows, off_rows,
                                                on_brake, on_end,
                                                off_brake, off_end,
                                                f"{t} — vehicle trajectory (pos_x vs pos_y)"))
        lines.append(f"![trajectory]({traj_svg})")
        lines.append("")

    return lines


